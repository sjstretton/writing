"""Build the literature download list and Windows batch file for the carbon-pricing series.

Reads every 5.Notes/Downloads-*.csv in the carbon-pricing paper folders (B Working Papers/1.CarbonPricing,
and 6.ModularUpgrades/6.1 for the Total Effective Carbon Price)
(columns: key,title,doi,url_tried,status,local_file) and writes, beside this script's
Run folder:
  E Writing Instructions/Scripts/Papers/Run/Download-Literature.bat   curl downloads into each paper's 4.ExternalPapers
  E Writing Instructions/Scripts/Papers/Reference/Literature-Downloads.md   automatic list + manual-download list

Status values (written by check_literature_access.py):
  downloaded         the cloud session already has it: nothing for Stephen to do
  open-blocked-here  free direct PDF the cloud session could not reach: in the batch file
  open-landing-page  free, but only via a web page: open in a browser (manual list)
  paywalled-manual   needs a library login (manual list)
  not-found          no record found (manual list)
Run from the repo root:  python "E Writing Instructions/Scripts/Papers/Steps/build_download_list.py"
"""
import csv
import re
from pathlib import Path

ROOT = Path("B Working Papers")
auto, manual, have, seen = [], [], [], set()
for f in sorted(list(ROOT.glob("1.CarbonPricing/*/5.Notes/Downloads-*.csv")) + list(ROOT.glob("6.ModularUpgrades/6.1.*/5.Notes/Downloads-*.csv"))):
    paper_dir = f.parent.parent
    with open(f, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            key = (r.get("key") or "").strip()
            if not key or key in seen:
                continue
            seen.add(key)
            url = (r.get("url_tried") or "").strip()
            doi = (r.get("doi") or "").strip()
            status = (r.get("status") or "").strip()
            title = (r.get("title") or "").strip()
            if status == "downloaded":
                have.append((paper_dir.name, key, title))
            elif status in ("open-blocked-here", "open-url-not-fetched") and url.startswith("http"):
                auto.append((paper_dir, key, title, url))
            else:
                manual.append((paper_dir.name, key, title, doi, url, status))

bat = ["@echo off", "rem Downloads open-access literature for the carbon-pricing series.",
       "rem Generated by E Writing Instructions/Scripts/Papers/Steps/build_download_list.py.",
       "setlocal", "set ROOT=%~dp0..\\..",
       "rem Links that fail go into a page that opens at the end.",
       'set MISS=%~dp0Literature-OpenInBrowser.html',
       '> "%MISS%" echo ^<html^>^<body^>^<h3^>Publisher blocked the download: open each link, save the PDF into the paper\'s 4.ExternalPapers folder^</h3^>^<ol^>',
       ""]
for paper_dir, key, title, url in auto:
    rel = str(paper_dir.relative_to(ROOT)).replace("/", "\\")
    safe = re.sub(r"[^A-Za-z0-9_-]", "", key)
    bat.append(f'if not exist "%ROOT%\\{rel}\\4.ExternalPapers" mkdir "%ROOT%\\{rel}\\4.ExternalPapers"')
    url = url.replace("%", "%%")  # cmd expands % even inside quotes
    out = f'"%ROOT%\\{rel}\\4.ExternalPapers\\{safe}.pdf"'
    # Keep the file only if it really is a PDF; some open-access links land on an HTML page.
    # Either way a failure is listed, with its link, in the page opened at the end.
    name = re.sub(r"[^A-Za-z0-9 ,.:'-]", "", title)[:90]
    miss = f'echo ^<li^>^<a href="{url}"^>{safe}^</a^> {name} - {rel}^</li^>>>"%MISS%"'
    bat.append(f'if not exist {out} (curl -L --fail -sS -o {out} "{url}" && (findstr /m /b /c:"%%PDF" {out} >nul || (del {out} & echo NOT A PDF: {key} & {miss})) || (echo FAILED: {key} & {miss}))')
bat += ["", '>> "%MISS%" echo ^</ol^>^</body^>^</html^>',
        "echo.", "echo Done. Most publishers block automated downloads, so FAILED is normal.",
        "echo The page now opening lists every paper that failed, with its link.",
        "echo Papers that need a library login: E Writing Instructions\\Scripts\\Papers\\Reference\\Literature-Downloads.md",
        'start "" "%MISS%"', "pause"]
(Path("E Writing Instructions/Scripts/Papers/Run/Download-Literature.bat")).write_text("\r\n".join(bat), encoding="utf-8")

label = {"open-landing-page": "free: open the page, then download", "paywalled-manual": "library login needed", "not-found": "not found: search by title"}
md = ["# Literature downloads for the carbon-pricing series", "",
      f"- **Automatic, {len(auto)} papers:** free PDFs the cloud session could not reach. Run `E Writing Instructions/Scripts/Papers/Run/Download-Literature.bat` on your PC; it saves each into the paper's `4.ExternalPapers/` and prints FAILED for any that refuse (most publishers block automated downloads) and NOT A PDF for any link that returns a web page. At the end it opens `E Writing Instructions/Scripts/Papers/Run/Literature-OpenInBrowser.html`, a clickable list of every paper that failed, to download by hand.",
      f"- **Manual, {len(manual)} papers:** free-but-via-a-web-page, library login, or not found. For later.",
      f"- **Already available to the agent, {len(have)} papers:** nothing to do.", "",
      "## Manual downloads (for later)", "", "| Paper folder | Key | Title | DOI / link | What to do |", "|---|---|---|---|---|"]
for folder, key, title, doi, url, status in sorted(manual, key=lambda r: (r[5], r[0], r[1])):
    status = label.get(status, status)
    link = f"https://doi.org/{doi}" if doi else url
    md.append(f"| {folder} | {key} | {title} | {link} | {status} |")
md += ["", "## Automatic downloads", "", "| Paper folder | Key | Title | URL |", "|---|---|---|---|"]
for paper_dir, key, title, url in auto:
    md.append(f"| {paper_dir.name} | {key} | {title} | {url} |")
md += ["", "## Already available to the agent", "", "| Paper folder | Key | Title |", "|---|---|---|"]
for folder, key, title in have:
    md.append(f"| {folder} | {key} | {title} |")
(Path("E Writing Instructions/Scripts/Papers/Reference/Literature-Downloads.md")).write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"{len(auto)} automatic, {len(manual)} manual, {len(have)} already available")
