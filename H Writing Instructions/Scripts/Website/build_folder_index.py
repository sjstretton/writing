"""Write an index.html at the top of each paper folder ("C Policy and FInance", "D Modelling") that lists every
section and paper with relative links to the files themselves: the master .qmd, the working paper, the brief,
the slides and the section overviews. Open it in a browser from the folder (or a synced copy) to browse the
documents locally; the links work wherever the folder is, because they are relative.

It is generated, not a master: it is rewritten on every compile from the folders and the masters' titles.
Compile-Website.bat runs it. It needs nothing but Python.
"""
import html
from urllib.parse import quote
from site_config import PARTS, paper_folders, paper_name, master_qmd, section_folder
from build_research_pages import front_matter

CSS = """body{font-family:Georgia,'Source Serif Pro',serif;max-width:860px;margin:2em auto;padding:0 16px;line-height:1.5;color:#222}
h1{font-weight:normal}h2{margin-top:1.8em;border-bottom:1px solid #ddd;font-weight:normal}
.p{margin:.9em 0}.t{font-weight:bold}.s{font-style:italic;color:#555}.l a{margin-right:1em}a{color:#1a5490}
.note{color:#777;font-size:.9em}@media(prefers-color-scheme:dark){body{background:#1e1e1e;color:#ddd}a{color:#8ab4f8}}"""


def a(root, path, label):
    if not path or not path.exists():
        return ""
    rel = path.relative_to(root).as_posix()
    return f'<a href="{quote(rel)}">{html.escape(label)}</a>'


def build(part):
    root = part["root"]
    out = [f"<!doctype html><html lang='en'><head><meta charset='utf-8'>"
           f"<meta name='viewport' content='width=device-width,initial-scale=1'>"
           f"<title>{html.escape(part['title'])}: papers</title><style>{CSS}</style></head><body>",
           "<!-- GENERATED by H Writing Instructions/Scripts/Website/build_folder_index.py on every compile. "
           "Not a master: edits here are lost. -->",
           f"<h1>{html.escape(part['title'])}</h1>",
           "<p class='note'>Every paper in this folder, with links to its files. The <b>master</b> is the .qmd; "
           "the Word files are made from it. Generated on each website compile.</p>"]
    for sec in part["sections"]:
        folder = section_folder(part, sec)
        num = sec[0].split(".")[0]
        out.append(f"<h2>{num}. {html.escape(sec[2])}</h2>")
        ov = folder / f"{num}.0.Overview"
        ovq = next(iter(sorted(ov.glob("*.qmd"))), None) if ov.is_dir() else None
        links = [a(root, ovq, "Overview (master qmd)"),
                 a(root, ovq.with_suffix(".docx") if ovq else None, "Overview (docx)"),
                 a(root, ov / "1.Presentation" / sec[5] if sec[5] else None, "Section slides (pptx)")]
        links = [l for l in links if l]
        if links:
            out.append(f"<div class='l'>{''.join(links)}</div>")
        for pf in paper_folders(part, sec):
            q = master_qmd(pf)
            name = paper_name(pf)
            meta = front_matter(q) if q else {}
            pnum = ".".join(pf.name.split(".")[:2])
            pres = pf / "1.Presentation"
            links = [a(root, q, "Master (qmd)"), a(root, pf / f"{name}.docx", "Working paper (docx)"),
                     a(root, pres / f"Brief-{name}.qmd", "Brief master (qmd)"),
                     a(root, pres / f"Brief-{name}.docx", "Brief (docx)"),
                     a(root, pres / f"Slides-{name}.pptx", "Slides (pptx)"), a(root, pf, "Folder")]
            out.append(f"<div class='p'><div class='t'>{pnum} {html.escape(meta.get('title', name))}</div>"
                       + (f"<div class='s'>{html.escape(meta['subtitle'])}</div>" if meta.get("subtitle") else "")
                       + f"<div class='l'>{''.join(l for l in links if l)}</div></div>")
    out.append("</body></html>")
    (root / "index.html").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {root / 'index.html'}")


def main():
    for part in PARTS:
        build(part)


if __name__ == "__main__":
    main()
